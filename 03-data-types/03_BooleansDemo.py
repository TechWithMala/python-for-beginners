#Booleans(True/False) demo...

#returns true or false when the condition/expression is evaluated
print(7>2)
print(7==9)

#use bool() to evaluate variables
name = "Bob"
age = 40
height = 6.2

print(".....use bool() to evaluate variables")
print(bool(name))
print(bool(age))
print(bool(height))

#use bool() to evaluate values
print(".....use bool() to evaluate values....")
print(bool("Python programming language is fun to learn..."))
print(bool(15))
print(bool(False))
print(bool(""))
print(bool(0))
print(bool(None))