#Python casting(specify a datatype to a variable) demo...

#Integers casting using int() constructor
intNum1 = int(8)
intNum2 = int(8.8)
intNum3 = int('8')

print(".....integers....")
print(intNum1)
print(intNum2)
print(intNum3)

#Floats casting using float() constructor
floatNum1 = float(3)
floatNum2 = float(3.3)
floatNum3 = float('3')

print(".....floats.....")
print(floatNum1)
print(floatNum2)
print(floatNum3)

#Strings casting using str() constructor
str1 = str('python')
str2 = str(4)
str3 = str(4.4)

print(".....strings.....")
print(str1)
print(str2)
print(type(str2))
print(str3)